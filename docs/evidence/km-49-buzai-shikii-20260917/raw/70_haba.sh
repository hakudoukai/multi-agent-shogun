#!/bin/bash
# 70_haba.sh ―― ★閾の位置が結論を動かすか★(己の都合で閾を選んだのでない事の測り)。
# 不感帯 91,480〜2,632,943 を跨いで閾を振り、鳴る本數が何処で変るかを見る。
set -u
MON="${1:?本器}"; NE="${2:?歩き根}"; NUL="${3:?NUL の置き場(歩き根の外)}"
find "$NE" -type f -print0 > "$NUL"
printf '%s\n' "刻 = $(date '+%Y-%m-%dT%H:%M:%S') / 根 = ${NE}"
printf '%s\n' "閾           鳴る本數  閾超の和      出目"
for t in 1 91479 91480 91481 524288 1048576 2097152 2632942 2632943 2632944 2634088 2634089 10485760; do
  o="$(BUZAI_MAX_BYTES="$t" bash "$MON" --from0 < "$NUL" 2>&1)"; rc=$?
  n="$(printf '%s\n' "$o" | grep -c '★部材 閾超')"
  w="$(printf '%s\n' "$o" | sed -n 's/.*閾超の和 \([0-9]*\) byte.*/\1/p')"
  printf '%-12s %-9s %-13s rc=%s\n' "$t" "$n" "${w:-?}" "$rc"
done
printf '%s\n' "★不感帯の内(91,480〜2,632,943)では鳴る本數が動かぬ ∴ 閾の位置は結論を選んで居らぬ。★"
