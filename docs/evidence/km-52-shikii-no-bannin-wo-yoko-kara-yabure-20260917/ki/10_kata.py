"""10_kata.py — 22形の正本。專任3 第49弾 ㋐01〜㋐22 を逐語で持つ。
   形は (札, 名, 値) の三つ組。値 None は ★未設定★ を表す(env から除く)。
   ★NUL 入り(㋐22)は env へ載らぬ★ ゆゑ値は bytes で持ち、載せる段で例外を捕へる。
"""
KATA = [
    ("01", "未設定",            None),
    ("02", "空文字",            ""),
    ("03", "空白のみ(SP)",      " "),
    ("04", "空白のみ(TAB)",     "\t"),
    ("05", "全角空白のみ",      "　"),
    ("06", "負値 -1",           "-1"),
    ("07", "負零 -0",           "-0"),
    ("08", "零 0",              "0"),
    ("09", "+50",               "+50"),
    ("10", "前後に空白",        " 50 "),
    ("11", "改行(末尾)",        "50\n"),
    ("12", "改行(中)",          "50\n9999"),
    ("13", "全角数字",          "５０"),
    ("14", "0x32",              "0x32"),
    ("15", "0o62",              "0o62"),
    ("16", "先頭零 007",        "007"),
    ("17", "先頭零 010",        "010"),
    ("18", "2^63-1",            "9223372036854775807"),
    ("19", "2^63",              "9223372036854775808"),
    ("20", "極長桁(9x400)",     "9" * 400),
    ("21", "単位付 10m",        "10m"),
    ("22", "NUL 入り",          "50\x009999"),
]
assert len(KATA) == 22, len(KATA)
assert len({k[0] for k in KATA}) == 22

def byte_retsu(v):
    if v is None:
        return "(無)"
    b = v.encode("utf-8")
    s = " ".join("%02x" % c for c in b)
    return s if len(s) <= 60 else s[:57] + "…"
