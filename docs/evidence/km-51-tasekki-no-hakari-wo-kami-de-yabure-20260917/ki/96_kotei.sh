#!/bin/bash
# 96_kotei.sh ―― ★測つた版を其の場で己の束へ固定する★
#   由: 共有の歩き樹は他席が同刻に書き換へる。第51弾の最中、四本悉くが動いた(07:17:37/07:26:05)。
#       ∴「生器を読んだ」だけでは紙の行番が再現せぬ。★読んだ其の版★を束へ写して番号の錨とする。
#   ★写す先は己の束のみ。生器へは一字も書かぬ。★
# 使ひ方: 96_kotei.sh <写し先dir> <器1> <器2> ...
set -u
D="$1"; shift; mkdir -p "$D"
printf '#器\t凍結sha16\t写し先\t行数\n'
for f in "$@"; do
  b=$(basename "$f")
  cp "$f" "$D/$b"
  printf '%s\t%s\t%s\t%s\n' "$f" "$(shasum -a 256 "$D/$b" | cut -c1-16)" "$D/$b" "$(grep -c '' "$D/$b")"
done
